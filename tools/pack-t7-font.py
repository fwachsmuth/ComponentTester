#!/usr/bin/env python3
"""Pack the existing font losslessly, retaining every character mapping."""
import argparse
from collections import Counter
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def original_font():
    compiler = shutil.which('avr-gcc') or '/Applications/Arduino.app/Contents/Java/hardware/tools/avr/bin/avr-gcc'
    source = '#include "config.h"\n#include "common.h"\n#include "bitmaps/font_8x16_alt_hf.h"\n'
    result = subprocess.run([compiler, '-mmcu=atmega324p', '-DF_CPU=16000000UL',
                             '-I.', '-Ibitmaps', '-E', '-P', '-x', 'c', '-'],
                            cwd=ROOT, input=source, text=True, capture_output=True, check=True)
    arrays = []
    for name in ('FontData', 'FontTable'):
        body = re.search(r'const uint8_t ' + name + r'\[\].*?=\s*\{(.*?)\};', result.stdout, re.S)[1]
        arrays.append(bytes(int(value, 0) for value in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', body)))
    return arrays


def packed_header(raw, mapping):
    assert len(raw) == 119 * 16 and len(mapping) == 256
    changes, masks = [], []
    for start in range(0, len(raw), 16):
        previous = mask = 0
        for row, value in enumerate(raw[start:start + 16]):
            if value != previous:
                mask |= 1 << row
                changes.append(value)
            previous = value
        masks.append(mask)
    dictionary = [value for value, _ in Counter(changes).most_common(15)]
    tokens, offsets = [], []
    position = 0
    for glyph, mask in enumerate(masks):
        if glyph % 8 == 0:
            offsets.append(len(tokens))
        for row in range(16):
            if mask & (1 << row):
                value = changes[position]
                position += 1
                if value in dictionary:
                    tokens.append(dictionary.index(value))
                else:
                    tokens.extend((15, value >> 4, value & 15))
    packed = bytes((tokens[i] << 4) | (tokens[i+1] if i+1 < len(tokens) else 0)
                   for i in range(0, len(tokens), 2))
    assert all(mapping[c] == c - 16 for c in range(32, 127))
    special = [(c, value) for c, value in enumerate(mapping)
               if c >= 16 and not 32 <= c <= 126 and value != 255]
    text = '/* Generated by tools/pack-t7-font.py from font_8x16_alt_hf.h.\n'
    text += ' * Same bitmap data and license; all pixels and character codes retained. */\n'
    for name, values, ctype in [('FontDictionary', dictionary, 'uint8_t'),
                              ('FontMasks', masks, 'uint16_t'),
                              ('FontOffsets', offsets, 'uint16_t'),
                              ('FontPacked', packed, 'uint8_t'),
                              ('FontLow', mapping[:16], 'uint8_t'),
                              ('FontHigh', [v for pair in special for v in pair], 'uint8_t')]:
        text += f'const {ctype} {name}[] PROGMEM = {{\n'
        for start in range(0, len(values), 16):
            text += '  ' + ','.join(str(value) for value in values[start:start+16]) + ',\n'
        text += '};\n'
    text += f'#define FONT_HIGH_COUNT {len(special)}\n'
    size = len(dictionary) + len(masks)*2 + len(offsets)*2 + len(packed) + 16 + len(special)*2
    return text, size


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw, mapping = original_font()
    header, size = packed_header(raw, mapping)
    output = ROOT / 'bitmaps' / 'font_8x16_alt_hf_packed.h'
    if args.check:
        assert output.read_text() == header, 'Packed font needs regeneration'
    else:
        output.write_text(header)
    print(f'Font data and mapping: {len(raw)+len(mapping)} -> {size} bytes.')
