#!/usr/bin/env python3
"""Deduplicate 30x32 bitmap rows without changing symbol IDs or pixels."""
import argparse
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]


def raw_symbols():
    compiler = shutil.which('avr-gcc') or '/Applications/Arduino.app/Contents/Java/hardware/tools/avr/bin/avr-gcc'
    source = '#include "config.h"\n#include "common.h"\n#include "bitmaps/symbols_30x32_hf.h"\n'
    result = subprocess.run([compiler, '-mmcu=atmega324p', '-DF_CPU=16000000UL',
                             '-I.', '-Ibitmaps', '-E', '-P', '-x', 'c', '-'],
                            cwd=ROOT, input=source, text=True, capture_output=True, check=True)
    body = re.search(r'const uint8_t SymbolData\[\].*?=\s*\{(.*?)\};', result.stdout, re.S)[1]
    return bytes(int(value, 0) for value in re.findall(r'0x[0-9a-fA-F]+|\b\d+\b', body))


def packed_header(raw):
    assert len(raw) == 15 * 128, 'Compact profile requires the standard 15 symbols'
    unique, indices = [], []
    for position in range(0, len(raw), 4):
        row = raw[position:position + 4]
        if row not in unique:
            unique.append(row)
        indices.append(unique.index(row))
    assert len(unique) <= 256
    assert b''.join(unique[index] for index in indices) == raw
    text = '/* Generated by tools/pack-t7-symbols.py from symbols_30x32_hf.h.\n'
    text += ' * Same bitmap data and license; shared rows preserve every pixel. */\n'
    for name, data in [('SymbolRows', b''.join(unique)), ('SymbolRowIndex', bytes(indices))]:
        text += f'const uint8_t {name}[] PROGMEM = {{\n'
        for position in range(0, len(data), 16):
            text += '  ' + ','.join(f'0x{value:02x}' for value in data[position:position + 16]) + ',\n'
        text += '};\n'
    return text, len(indices) + 4 * len(unique)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = raw_symbols()
    header, size = packed_header(raw)
    output = ROOT / 'bitmaps' / 'symbols_30x32_hf_packed.h'
    if args.check:
        assert output.read_text() == header, 'Packed symbols need regeneration'
    else:
        output.write_text(header)
    print(f'Symbol bitmaps: {len(raw)} -> {size} bytes; {len(raw)-size} bytes saved.')
